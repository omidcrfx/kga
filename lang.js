const defaultLang = "fa";

function getSavedLang() {
  const fromStorage = window.localStorage.getItem("lang");
  if (fromStorage && translations[fromStorage]) return fromStorage;
  return defaultLang;
}

function setLang(lang) {
  if (!translations[lang]) return;
  window.localStorage.setItem("lang", lang);
}

function applyLang(lang) {
  const dict = translations[lang] || translations[defaultLang];

  // Update html attributes
  const html = document.documentElement;
  html.lang = lang;
  html.dir = lang === "fa" ? "rtl" : "ltr";

  // body class
  document.body.classList.toggle("rtl-body", lang === "fa");
  document.body.classList.toggle("ltr-body", lang === "en");

  // Meta
  const titleEl = document.querySelector("title");
  if (titleEl && dict.meta_title) titleEl.textContent = dict.meta_title;
  const descEl = document.querySelector('meta[name="description"]');
  if (descEl && dict.meta_description)
    descEl.setAttribute("content", dict.meta_description);

  // All elements with data-i18n
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  // Inputs / placeholders
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict[key]) {
      el.setAttribute("placeholder", dict[key]);
    }
  });

  // Buttons with aria-label
  document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria-label");
    if (dict[key]) {
      el.setAttribute("aria-label", dict[key]);
    }
  });

  // Update language toggle text
  const langToggle = document.querySelector("[data-lang-toggle]");
  if (langToggle) {
    langToggle.textContent = dict.nav_language;
  }
}

function changeLanguage(nextLang) {
  setLang(nextLang);
  applyLang(nextLang);
}

document.addEventListener("DOMContentLoaded", () => {
  const lang = getSavedLang();
  applyLang(lang);
});


